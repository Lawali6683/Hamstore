let lang = "en";

export const getLang = () => lang;

export function t(key, vars) {
  let s = (D[lang] && D[lang][key]) || D.en[key] || key;
  if (vars) Object.keys(vars).forEach(k => { s = s.split("{" + k + "}").join(vars[k]); });
  return s;
}

function apply(l) {
  lang = l === "ha" ? "ha" : "en";
  document.documentElement.lang = lang;
  document.documentElement.dataset.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  document.querySelectorAll("[data-lang-btn]").forEach(b => { b.setAttribute("aria-pressed", String(b.dataset.langBtn === lang)); });
  const sw = document.getElementById("langSw");
  if (sw) sw.dataset.on = lang;
  window.dispatchEvent(new CustomEvent("langchange", { detail: lang }));
}

const read = k => { try { return localStorage.getItem(k) || ""; } catch (e) { return ""; } };
const write = (k, v) => { try { localStorage.setItem(k, v); } catch (e) {} };

export function setLang(l) {
  write("hs_lang", l);
  write("hs_lang_manual", "1");
  apply(l);
}

export async function initLang() {
  document.querySelectorAll("[data-lang-btn]").forEach(b => b.addEventListener("click", () => setLang(b.dataset.langBtn)));
  if (read("hs_lang_manual") === "1" && read("hs_lang")) return apply(read("hs_lang"));
  const langs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ""]).map(x => String(x).toLowerCase());
  const device = langs.some(x => x === "ha" || x.startsWith("ha-")) ? "ha" : "";
  apply(device || read("hs_lang") || "en");
  if (device) return write("hs_lang", "ha");
  try {
    const res = await fetch("/api/lang", { cache: "no-store" });
    const j = await res.json();
    if (read("hs_lang_manual") !== "1" && (j.lang === "ha" || j.lang === "en")) {
      write("hs_lang", j.lang);
      if (j.lang !== lang) apply(j.lang);
    }
  } catch (e) {}
}


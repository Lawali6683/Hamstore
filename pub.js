let approxPromise = null;

export function approxLocation() {
  if (!approxPromise) {
    approxPromise = fetch("/api/lang", { cache: "no-store" })
      .then(r => r.json())
      .then(j => {
        const lat = Number(j.lat);
        const lng = Number(j.lng);
        return j.lat !== null && j.lat !== undefined && j.lat !== "" && Number.isFinite(lat) && Number.isFinite(lng) ? { lat, lng } : null;
      })
      .catch(() => null);
  }
  return approxPromise;
}

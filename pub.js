export function km(a, b) {
  const r = x => (x * Math.PI) / 180;
  const h = Math.sin(r(b.lat - a.lat) / 2) ** 2 + Math.cos(r(a.lat)) * Math.cos(r(b.lat)) * Math.sin(r(b.lng - a.lng) / 2) ** 2;
  return 12742 * Math.asin(Math.sqrt(h));
}

const toMin = s => {
  const [h, m] = String(s || "").split(":").map(Number);
  return Number.isFinite(h) && Number.isFinite(m) ? h * 60 + m : null;
};

export function branchStatus(b) {
  const o = toMin(b.opens);
  const c = toMin(b.closes);
  if (o === null || c === null) return null;
  const p = new Intl.DateTimeFormat("en-GB", { timeZone: "Africa/Lagos", hour: "2-digit", minute: "2-digit", hour12: false }).formatToParts(new Date());
  const n = (Number(p.find(x => x.type === "hour").value) % 24) * 60 + Number(p.find(x => x.type === "minute").value);
  const open = o <= c ? n >= o && n < c : n >= o || n < c;
  return open ? "open" : "closed";
}

